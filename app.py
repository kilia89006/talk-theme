st.title("トークテーマアプリ")

# --- アプリの状態管理 ---
if "step" not in st.session_state:
    st.session_state.step = "idle"
if "chosen_genre" not in st.session_state:
    st.session_state.chosen_genre = None
if "chosen_theme" not in st.session_state:
    st.session_state.chosen_theme = None

all_genres = list(talk_themes.keys())

# --- 【中央の大きなボタン】状態によって役割が変わる1つのボタン ---
left_col, center_col, right_col = st.columns([1, 2, 1])

with center_col:
    # 状態1: 最初（ジャンル開始）
    if st.session_state.step == "idle":
        if st.button("ジャンルを決める 🥁", type="primary", use_container_width=True):
            st.session_state.step = "genre_roll"
            st.rerun()

    # 状態2: ジャンルドラムロール中（手動ストップ！）
    elif st.session_state.step == "genre_roll":
        if st.button("🛑 ジャンル確定！", type="primary", use_container_width=True):
            st.session_state.chosen_genre = random.choice(all_genres)
            st.session_state.step = "theme_roll"
            st.rerun()

    # 状態3: お題ドラムロール中（手動ストップ！）
    elif st.session_state.step == "theme_roll":
        if st.button("🛑 テーマ確定！", type="primary", use_container_width=True):
            current_genre_themes = talk_themes[st.session_state.chosen_genre]
            st.session_state.chosen_theme = random.choice(current_genre_themes)
            st.session_state.step = "all_done"
            st.rerun()

    # 状態4: 完了後（リセット）
    elif st.session_state.step == "all_done":
        if st.button("🔄 もう一度あそぶ", use_container_width=True):
            st.session_state.step = "idle"
            st.session_state.chosen_genre = None
            st.session_state.chosen_theme = None
            st.rerun()

st.write("---")

# 表示エリア
status_text = st.empty()
genre_area = st.empty()
theme_area = st.empty()

# --- 1. ジャンルのドラムロール演出 ---
if st.session_state.step == "genre_roll":
    status_text.markdown("【Step 1】ジャンルを決めよう！")
    for _ in range(8):
        tmp_g = random.choice(all_genres)
        genre_area.info(f"🏷️ ジャンル： **{tmp_g}**")
        time.sleep(0.1)
    st.rerun()

# --- 2. お題のドラムロール演出 ---
if st.session_state.step == "theme_roll":
    status_text.markdown(f" ✨ ジャンル：【{st.session_state.chosen_genre}】\n 【Step 2】テーマを決めよう")
    genre_area.success(f"🏷️ ジャンル： **【{st.session_state.chosen_genre}】**")
    
    current_genre_themes = talk_themes[st.session_state.chosen_genre]
    for _ in range(8):
        tmp_t = random.choice(current_genre_themes)
        theme_area.info(f"👉 お題： {tmp_t}")
        time.sleep(0.06)
    st.rerun()

# --- 3. 最終結果表示 ---
if st.session_state.step == "all_done":
    status_text.subheader("🎉 今回のテーマ")
    genre_area.success(f" 🏷️ ジャンル：【{st.session_state.chosen_genre}】")
    theme_area.warning(f" 👉 『{st.session_state.chosen_theme}』")
 
